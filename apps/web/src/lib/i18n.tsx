export const dictionaries: Record<Lang, Dict> = { en, ar };
export type TKey = keyof Dict;

const I18nContext = createContext<{ lang: Lang; t: Dict }>({ lang: "en", t: en });

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  return <I18nContext.Provider value={{ lang, t: dictionaries[lang] }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function useSetLang() {
  const router = useRouter();
  return useCallback(
    (lang: Lang) => {
      document.cookie = `lang=${lang}; path=/; max-age=31536000; samesite=lax`;
      router.refresh();
    },
    [router],
  );
}

/** Human label for a backend code (status, reason, source); falls back to the code itself. */
export function codeLabel(t: Dict, value: string | null | undefined): string {
  if (!value) return "—";
  return t.codes[value] ?? value;
}

/** Default roles are stored in English; show them in the viewer's language. */
export function roleName(t: Dict, name: string): string {
  return t.roleNames[name] ?? name;
}

export function formatDate(value: string | null | undefined, lang: Lang, withTime = true, timeZone?: string): string {
  if (!value) return "—";
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-AE-u-nu-latn" : "en-GB", {
    day: "numeric",
    month: "short",
    timeZone,
    ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
  }).format(new Date(value));
}

export function formatMoney(value: number | string | null | undefined, currency: string, lang: Lang): string {
  if (value === null || value === undefined || value === "") return "—";
  const n = typeof value === "string" ? Number(value) : value;
  if (Number.isNaN(n)) return String(value);
  return new Intl.NumberFormat(lang === "ar" ? "ar-AE-u-nu-latn" : "en-AE", {
    style: "currency",
    currency,
    maximumFractionDigits: n % 1 === 0 ? 0 : 2,
  }).format(n);
}
